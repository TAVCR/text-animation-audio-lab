import React from 'react';
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { beforeEach, describe, expect, it } from 'vitest';
import { AnimationProvider, useAnimation } from '@/lib/AnimationContext';
import BackgroundBasicTab from '@/components/inspector/tabs/BackgroundBasicTab';
import CompositionBasicTab from '@/components/inspector/tabs/CompositionBasicTab';
import TextBasicTab from '@/components/inspector/tabs/TextBasicTab';

beforeEach(() => cleanup());

describe('integrated inspector tabs', () => {
  it('exposes real background controls', () => { render(<AnimationProvider><BackgroundBasicTab /></AnimationProvider>); expect(screen.getByRole('listbox', { name: 'Fondo' })).toBeTruthy(); expect(screen.getByLabelText('Número de partículas')).toBeTruthy(); expect(screen.getByLabelText('Color principal')).toBeTruthy(); });
  it('exposes real composition controls', () => { render(<AnimationProvider><CompositionBasicTab /></AnimationProvider>); expect(screen.getByLabelText('Relación de aspecto')).toBeTruthy(); expect(screen.getByLabelText('Resolución')).toBeTruthy(); expect(screen.getByLabelText('Duración')).toBeTruthy(); });
  it('expone controles de semitono solo al seleccionar N-B01 y actualiza la prop real', async () => {
    const Probe = () => { const { props } = useAnimation(); return <output data-testid="halftone-spacing">{props.halftoneSpacingPx}</output>; };
    render(<AnimationProvider><BackgroundBasicTab /><Probe /></AnimationProvider>);
    expect(screen.queryByLabelText('Espaciado')).toBeNull();
    const picker = screen.getAllByRole('listbox', { name: 'Fondo' })[0];
    fireEvent.click(within(picker).getByRole('option', { name: /Halftone Wave Field/i }));
    const spacing = await waitFor(() => screen.getByRole('slider', { name: 'Espaciado deslizador' }));
    expect((spacing as HTMLInputElement).value).toBe('28');
    fireEvent.change(spacing, { target: { value: '40' } });
    await waitFor(() => expect(screen.getByTestId('halftone-spacing').textContent).toBe('40'));
  });
  it('expone controles de bombilla solo al seleccionar N-B01 y actualiza la prop real', async () => {
    const Probe = () => { const { props } = useAnimation(); return <><output data-testid="neon-bulb-density">{props.neonBulbDensity}</output><output data-testid="neon-bulb-pattern">{props.neonBulbPattern}</output><output data-testid="neon-bulb-mix">{props.neonBulbPatternMix}</output><output data-testid="neon-bulb-backdrop">{props.particleBackdropColor}</output></>; };
    render(<AnimationProvider initialProps={{ particlePreset: 'neon-bulb-alternation' }}><BackgroundBasicTab /><Probe /></AnimationProvider>);
    expect(screen.queryByLabelText('Número de partículas')).toBeNull();
    expect(screen.queryByLabelText('Tamaño mínimo')).toBeNull();
    expect(screen.queryByLabelText('Tamaño máximo')).toBeNull();
    expect(screen.queryByLabelText('Color de fondo difuminado')).toBeTruthy();
    expect(screen.queryByLabelText('Cantidad de recortes')).toBeNull();
    const picker = screen.getByRole('listbox', { name: 'Fondo' });
    fireEvent.click(within(picker).getByRole('option', { name: /Neon Bulb Alternation/i }));
    const density = await waitFor(() => screen.getByRole('slider', { name: 'Densidad deslizador' }));
    expect((density as HTMLInputElement).value).toBe('40');
    fireEvent.change(density, { target: { value: '55' } });
    await waitFor(() => expect(screen.getByTestId('neon-bulb-density').textContent).toBe('55'));
    expect(screen.getByLabelText('Patrón principal')).toBeTruthy();
    expect(screen.getByTestId('neon-bulb-pattern').textContent).toBe('organic');
    expect(screen.queryByLabelText('Patrón secundario')).toBeNull();
    fireEvent.click(screen.getByLabelText('Combinar segundo patrón'));
    expect(screen.getByLabelText('Patrón secundario')).toBeTruthy();
    expect(screen.getByRole('slider', { name: 'Mezcla de patrones deslizador' })).toBeTruthy();
    fireEvent.change(screen.getByRole('slider', { name: 'Mezcla de patrones deslizador' }), { target: { value: '0.8' } });
    await waitFor(() => expect(screen.getByTestId('neon-bulb-mix').textContent).toBe('0.8'));
    fireEvent.change(screen.getByLabelText('Patrón principal'), { target: { value: 'horizontal' } });
    expect((screen.getByLabelText('Patrón secundario') as HTMLSelectElement).value).not.toBe('horizontal');
    expect(screen.queryByLabelText('Ángulo')).toBeNull();
    fireEvent.change(screen.getByLabelText('Patrón principal'), { target: { value: 'angular' } });
    expect(screen.getByRole('slider', { name: 'Ángulo deslizador' })).toBeTruthy();
    fireEvent.change(screen.getByLabelText('Patrón principal'), { target: { value: 'radial' } });
    expect(screen.getByRole('slider', { name: 'Centro X deslizador' })).toBeTruthy();
    expect(screen.getByRole('slider', { name: 'Centro Y deslizador' })).toBeTruthy();
  });
  it('expone controles Stellar condicionales y escribe en la autoridad compartida', async () => {
    const Probe = () => { const { props } = useAnimation(); return <output data-testid="stellar-state">{`${props.stellarDensity}:${props.stellarMotionMode}:${props.stellarDof}:${props.stellarNebula}`}</output>; };
    render(<AnimationProvider initialProps={{ particlePreset: 'stellar-depth-field' }}><BackgroundBasicTab /><Probe /></AnimationProvider>);
    expect(screen.queryByLabelText('Número de partículas')).toBeNull();
    expect(screen.queryByLabelText('Color principal')).toBeNull();
    expect((screen.getByLabelText('Densidad') as HTMLInputElement).value).toBe('320');
    expect(screen.getByLabelText('Movimiento espacial')).toBeTruthy();
    expect(screen.getByRole('slider', { name: 'Velocidad Z deslizador' })).toBeTruthy();
    expect(screen.getByRole('slider', { name: 'Estelas deslizador' })).toBeTruthy();
    fireEvent.change(screen.getByLabelText('Movimiento espacial'), { target: { value: 'drift' } });
    expect(screen.queryByLabelText('Velocidad Z')).toBeNull();
    expect(screen.queryByLabelText('Estelas')).toBeNull();
    expect(screen.getByRole('slider', { name: 'Variación térmica deslizador' })).toBeTruthy();
    fireEvent.change(screen.getByLabelText('Color estelar'), { target: { value: 'bicolor' } });
    expect(screen.queryByLabelText('Variación térmica')).toBeNull();
    expect(screen.getByLabelText('Color A')).toBeTruthy();
    expect(screen.getByLabelText('Color B')).toBeTruthy();
    fireEvent.change(screen.getByRole('slider', { name: 'Profundidad de campo deslizador' }), { target: { value: '0' } });
    expect(screen.queryByLabelText('Plano de enfoque')).toBeNull();
    fireEvent.change(screen.getByRole('slider', { name: 'Nebulosa deslizador' }), { target: { value: '0' } });
    expect(screen.queryByLabelText('Escala nebulosa')).toBeNull();
    fireEvent.change(screen.getByRole('slider', { name: 'Densidad deslizador' }), { target: { value: '480' } });
    await waitFor(() => expect(screen.getByTestId('stellar-state').textContent).toBe('480:drift:0:0'));
    fireEvent.doubleClick(screen.getByRole('slider', { name: 'Densidad deslizador' }));
    expect((screen.getByLabelText('Densidad') as HTMLInputElement).value).toBe('320');
  });
  it('oculta toda configuración para fondos de video prerenderizados', () => {
    render(<AnimationProvider initialProps={{ particlePreset: 'imported-video-1' }}><BackgroundBasicTab /></AnimationProvider>);
    expect(screen.queryByLabelText('Número de partículas')).toBeNull();
    expect(screen.queryByLabelText('Opacidad')).toBeNull();
    expect(screen.queryByLabelText('Velocidad')).toBeNull();
    expect(screen.queryByLabelText('Tamaño mínimo')).toBeNull();
    expect(screen.queryByLabelText('Tamaño máximo')).toBeNull();
    expect(screen.queryByLabelText('Color principal')).toBeNull();
  });
  it('no expone dirección de profundidad obsoleta en Ink Stamp Print', () => {
    render(<AnimationProvider initialProps={{ animationStyle: 'ink-stamp-print' }}><TextBasicTab /></AnimationProvider>);
    expect(screen.queryByLabelText('Dirección de profundidad')).toBeNull();
  });
  it('expone dos capas configurables y oculta líneas para lote en Dual Text Layers', () => {
    render(<AnimationProvider initialProps={{ animationStyle: 'dual-text-layers' }}><TextBasicTab /></AnimationProvider>);
    expect(screen.queryByLabelText('Líneas para lote')).toBeNull();
    expect(screen.queryByLabelText('Color')).toBeNull();
    expect(screen.getByLabelText('Color de capa 1')).toBeTruthy();
    expect(screen.getByText('Capa 1')).toBeTruthy();
    expect(screen.getByText('Capa 2')).toBeTruthy();
    expect(screen.getByLabelText('Posición X de capa 1')).toBeTruthy();
    expect(screen.getByLabelText('Posición Y de capa 1')).toBeTruthy();
    expect(screen.getByLabelText('Opacidad de capa 1')).toBeTruthy();
    expect(screen.getByLabelText('Posición X de capa 2')).toBeTruthy();
    expect(screen.getByLabelText('Posición Y de capa 2')).toBeTruthy();
    expect(screen.getByLabelText('Opacidad de capa 2')).toBeTruthy();
    expect(screen.getByRole('slider', { name: 'Posición X de capa 1 deslizador' })).toBeTruthy();
    expect(screen.getByRole('slider', { name: 'Posición Y de capa 1 deslizador' })).toBeTruthy();
    expect(screen.getByRole('slider', { name: 'Opacidad de capa 1 deslizador' })).toBeTruthy();
    expect(screen.getByRole('slider', { name: 'Posición X de capa 2 deslizador' })).toBeTruthy();
    expect(screen.getByRole('slider', { name: 'Posición Y de capa 2 deslizador' })).toBeTruthy();
    expect(screen.getByRole('slider', { name: 'Opacidad de capa 2 deslizador' })).toBeTruthy();
    fireEvent.doubleClick(screen.getByRole('slider', { name: 'Posición X de capa 1 deslizador' }));
    expect((screen.getByLabelText('Posición X de capa 1') as HTMLInputElement).value).toBe('0');
    fireEvent.doubleClick(screen.getByRole('slider', { name: 'Posición Y de capa 2 deslizador' }));
    expect((screen.getByLabelText('Posición Y de capa 2') as HTMLInputElement).value).toBe('0');
  });
});
